// Copies the agent skill (plugins/webhooks-cc/skills/webhooks-cc) into
// src/skill-files.ts, so both MCP servers can serve it with the package
// alone. Run after changing the skill; a test fails when the copy is stale.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skill = join(here, "../../../plugins/webhooks-cc/skills/webhooks-cc");
const out = join(here, "../src/skill-files.ts");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = Object.fromEntries(
  walk(skill)
    .map((path) => [relative(skill, path).split("\\").join("/"), readFileSync(path, "utf8")])
    .sort(([a], [b]) => a.localeCompare(b))
);

writeFileSync(
  out,
  [
    "// Generated by scripts/bundle-skill.mjs from plugins/webhooks-cc/skills/webhooks-cc. Do not edit.",
    "",
    'export const SKILL_NAME = "webhooks-cc";',
    "",
    `export const SKILL_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};`,
    "",
  ].join("\n")
);
console.log(`bundled ${Object.keys(files).length} skill files`);
